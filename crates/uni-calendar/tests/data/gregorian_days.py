"""Writes gregorian_days.txt, the independent oracle for tests/gregorian.rs (spec 006, SC-005).

For each proleptic Gregorian year 1 to 4000, one line: the year, the ordinal of 1 January
(day 1 is 1 January of year 1) from Python's `datetime.date.toordinal`, and the twelve month
lengths from `calendar.monthrange`. Python's implementation shares no code with the calendar
engine, so agreeing with it is evidence the engine is right (constitution VI).

Standard library only. Run from the repository root:

    python crates/uni-calendar/tests/data/gregorian_days.py > crates/uni-calendar/tests/data/gregorian_days.txt
"""

import calendar
import datetime
import sys

FIRST, LAST = 1, 4000


def main():
    # "\n" line endings on every platform, so the committed file is reproduced exactly.
    sys.stdout.reconfigure(newline="\n")
    # Only the version number, not the build details, which differ from machine to machine.
    version = sys.version.split()[0]
    print("# Generated by crates/uni-calendar/tests/data/gregorian_days.py")
    print(f"# Python {version}: datetime.date(year, 1, 1).toordinal() and calendar.monthrange")
    print("# year jan1_ordinal m1 m2 m3 m4 m5 m6 m7 m8 m9 m10 m11 m12")
    for year in range(FIRST, LAST + 1):
        ordinal = datetime.date(year, 1, 1).toordinal()
        months = [calendar.monthrange(year, month)[1] for month in range(1, 13)]
        print(year, ordinal, *months)


if __name__ == "__main__":
    main()
